/* ---------- runtime ---------- */

let _lang = 'zh';
try {
  const saved = localStorage.getItem('mb-lang');
  if (saved === 'en' || saved === 'zh') _lang = saved;
} catch { /* no localStorage */ }

function t(key, ...args) {
  let s = (I18N[_lang] && I18N[_lang][key]) || I18N.zh[key] || key;
  if (args.length) {
    for (let i = 0; i < args.length; i++) {
      s = s.replace(new RegExp('\\{' + i + '\\}', 'g'), String(args[i]));
    }
  }
  return s;
}

function getLang() { return _lang; }

function setLang(lang) {
  _lang = (lang === 'en') ? 'en' : 'zh';
  try { localStorage.setItem('mb-lang', _lang); } catch { /* */ }
}

function applyLang() {
  document.querySelectorAll('[data-i18n]').forEach((el) => {
    el.textContent = t(el.dataset.i18n);
  });
  document.querySelectorAll('[data-i18n-title]').forEach((el) => {
    el.title = t(el.dataset.i18nTitle);
  });
  document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
    el.placeholder = t(el.dataset.i18nPh);
  });
}
